import numpy as np
# --------------------------------------------------------------------
# 1. Creacion de Matriz
#---------------------------------------------------------------------
A = np.random.randint(200, 255, (5,5))
print(A)
#---------------------------------------------------------------------
# 2. constrante y brillo
#---------------------------------------------------------------------
alpha = 0.5
beta = -50
A_nueva = (alpha * A.astype(float)) +  beta
#---------------------------------------------------------------------
# 3. Clip
#---------------------------------------------------------------------
A_nueva = np.clip(A_nueva, 0, 255).astype(np.uint8)
#---------------------------------------------------------------------
# 4. Matriz
#---------------------------------------------------------------------
print("Matriz Nueva")
print(A_nueva)